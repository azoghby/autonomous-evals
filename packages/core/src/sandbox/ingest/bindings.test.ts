import { describe, expect, it, vi } from "vitest";
import type { ToolSpec } from "../spec";
import { parseDdl, proposeBindings, type GenerateBindings } from "./bindings";

const DDL = `
CREATE TABLE sandbox_clock (frozen_now timestamptz NOT NULL);
CREATE FUNCTION sandbox_now() RETURNS timestamptz LANGUAGE sql STABLE AS $$ SELECT frozen_now FROM sandbox_clock LIMIT 1 $$;
CREATE TABLE customers (
  id integer PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL,
  tier text NOT NULL DEFAULT 'standard' CHECK (tier IN ('standard','plus','vip')),
  created_at timestamptz NOT NULL DEFAULT sandbox_now()
);
CREATE TABLE orders (
  id integer PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id),
  status text NOT NULL CHECK (status IN ('processing','shipped')),
  placed_at timestamptz NOT NULL,
  total numeric(10,2) NOT NULL CHECK (total >= 0)
);
CREATE TABLE refunds (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id),
  customer_id integer NOT NULL REFERENCES customers(id),
  amount numeric(10,2) NOT NULL CHECK (amount > 0),
  reason text NOT NULL,
  status text NOT NULL DEFAULT 'processed',
  created_at timestamptz NOT NULL DEFAULT sandbox_now()
);
CREATE TABLE tickets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id),
  subject text NOT NULL,
  body text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'open',
  priority text NOT NULL DEFAULT 'normal',
  created_at timestamptz NOT NULL DEFAULT sandbox_now(),
  updated_at timestamptz NOT NULL DEFAULT sandbox_now(),
  UNIQUE (customer_id, subject)
);
CREATE TABLE kb_articles (id integer PRIMARY KEY, title text NOT NULL, body text NOT NULL);
CREATE TABLE sandbox_outbox (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind text NOT NULL, payload jsonb NOT NULL);
`;

const num = { type: "integer" };
const str = { type: "string" };
function tool(name: string, properties: Record<string, unknown>, required: string[], effect: ToolSpec["effect"] = "read", description = name): ToolSpec {
  return {
    name, description, effect, source: "test",
    inputSchema: { type: "object", properties, required },
    binding: { kind: "simulated", instructions: "", readsTables: [], recordsOutbox: false },
  };
}
const sqlOf = (t: ToolSpec): string[] => (t.binding.kind === "sql" ? t.binding.statements : []);

describe("parseDdl", () => {
  const t = parseDdl(DDL);
  it("parses columns, defaults, identity and pks", () => {
    expect(Object.keys(t)).toEqual(["sandbox_clock", "customers", "orders", "refunds", "tickets", "kb_articles", "sandbox_outbox"]);
    const refunds = t.refunds!.columns;
    expect(refunds.map((c) => c.name)).toEqual(["id", "order_id", "customer_id", "amount", "reason", "status", "created_at"]);
    expect(refunds[0]).toMatchObject({ isPk: true, hasDefault: true, notNull: true });
    expect(refunds[3]).toMatchObject({ type: "numeric(10,2)", notNull: true, hasDefault: false });
    expect(t.customers!.columns.find((c) => c.name === "tier")).toMatchObject({ hasDefault: true, notNull: true, type: "text" });
    expect(t.orders!.columns.find((c) => c.name === "placed_at")!.type).toBe("timestamptz");
  });
  it("ignores table-level constraints", () => {
    expect(t.tickets!.columns.map((c) => c.name)).not.toContain("UNIQUE");
    expect(t.tickets!.columns).toHaveLength(8);
  });
});

describe("proposeBindings deterministic rules", () => {
  it("get_order maps order_id to id", async () => {
    const orig = tool("get_order", { order_id: num }, ["order_id"]);
    const { tools, report } = await proposeBindings([orig], DDL);
    expect(tools[0]!.binding).toMatchObject({ kind: "sql", resultShape: "row", statements: ["SELECT * FROM orders WHERE id = :order_id LIMIT 1"] });
    expect(report.get_order).toEqual({ origin: "rule", warnings: [] });
    expect(orig.binding.kind).toBe("simulated"); // no mutation
    expect(tools[0]).not.toBe(orig);
  });

  it("lookup_customer by email", async () => {
    const { tools } = await proposeBindings([tool("lookup_customer", { email: str }, ["email"])], DDL);
    expect(sqlOf(tools[0]!)).toEqual(["SELECT * FROM customers WHERE email = :email LIMIT 1"]);
  });

  it("list_orders builds optional filters, ordering and limit", async () => {
    const { tools } = await proposeBindings([tool("list_orders", { customer_id: num, status: str, limit: num }, [])], DDL);
    const b = tools[0]!.binding;
    expect(b).toMatchObject({ kind: "sql", resultShape: "rows" });
    expect(sqlOf(tools[0]!)[0]).toBe(
      "SELECT * FROM orders WHERE (CAST(:customer_id AS integer) IS NULL OR customer_id = :customer_id) AND (CAST(:status AS text) IS NULL OR status = :status) ORDER BY placed_at DESC, id DESC LIMIT COALESCE(CAST(:limit AS integer), 20)",
    );
  });

  it("list with a required param uses plain equality", async () => {
    const { tools } = await proposeBindings([tool("list_tickets", { customer_id: num }, ["customer_id"])], DDL);
    expect(sqlOf(tools[0]!)[0]).toContain("WHERE customer_id = :customer_id ORDER BY created_at DESC, id DESC LIMIT 20");
  });

  it("create_refund inserts matched columns", async () => {
    const { tools } = await proposeBindings(
      [tool("create_refund", { order_id: num, customer_id: num, amount: { type: "number" }, reason: str }, ["order_id", "customer_id", "amount", "reason"], "write")],
      DDL,
    );
    expect(sqlOf(tools[0]!)).toEqual(["INSERT INTO refunds (order_id, customer_id, amount, reason) VALUES (:order_id, :customer_id, :amount, :reason) RETURNING *"]);
    expect(tools[0]!.binding).toMatchObject({ resultShape: "row" });
  });

  it("create_ticket coalesces optional NOT NULL DEFAULT columns", async () => {
    const { tools } = await proposeBindings(
      [tool("create_ticket", { customer_id: num, subject: str, body: str, priority: str }, ["customer_id", "subject"], "write")],
      DDL,
    );
    expect(sqlOf(tools[0]!)[0]).toBe(
      "INSERT INTO tickets (customer_id, subject, body, priority) VALUES (:customer_id, :subject, COALESCE(:body, ''), COALESCE(:priority, 'normal')) RETURNING *",
    );
  });

  it("create rejects when a NOT NULL column without default is missing", async () => {
    const { tools, report } = await proposeBindings([tool("create_refund", { order_id: num, amount: num }, ["order_id", "amount"], "write")], DDL);
    expect(tools[0]!.binding.kind).toBe("simulated");
    expect(report.create_refund!.origin).toBe("simulated");
  });

  it("update_ticket coalesces columns and bumps updated_at", async () => {
    const { tools } = await proposeBindings(
      [tool("update_ticket", { ticket_id: num, status: str, priority: str }, ["ticket_id"], "write")],
      DDL,
    );
    expect(sqlOf(tools[0]!)).toEqual([
      "UPDATE tickets SET status = COALESCE(:status, status), priority = COALESCE(:priority, priority), updated_at = sandbox_now() WHERE id = :ticket_id RETURNING *",
    ]);
  });

  it("uses only named params, all declared in the schema", async () => {
    const { tools } = await proposeBindings(
      [tool("get_order", { order_id: num }, ["order_id"]), tool("update_ticket", { ticket_id: num, status: str }, ["ticket_id"], "write")],
      DDL,
    );
    for (const t of tools) for (const s of sqlOf(t)) expect(s).not.toMatch(/\$\d/);
  });

  it("search with free-text param falls through to simulated", async () => {
    const { tools, report } = await proposeBindings([tool("search_kb", { query: str }, ["query"], "read", "Search the knowledge base")], DDL);
    expect(report.search_kb!.origin).toBe("simulated");
    expect(tools[0]!.binding).toMatchObject({ kind: "simulated", recordsOutbox: false, readsTables: ["kb_articles"] });
  });
});

describe("proposeBindings fallbacks and precedence", () => {
  const nonCrud = tool("check_refund_eligibility", { order_id: num }, ["order_id"], "read", "Check whether an order is refundable");

  it("uses generate for a non-CRUD tool", async () => {
    const generate: GenerateBindings = vi.fn(async () => ({ statements: ["SELECT (status = 'shipped') AS eligible FROM orders WHERE id = :order_id"], resultShape: "row" as const }));
    const { tools, report } = await proposeBindings([nonCrud], DDL, { generate });
    expect(report.check_refund_eligibility).toEqual({ origin: "llm", warnings: [] });
    expect(tools[0]!.binding.kind).toBe("sql");
    expect(generate).toHaveBeenCalledOnce();
  });

  it("downgrades unsafe generated SQL to simulated with a warning", async () => {
    const bad: Array<[string[], RegExp]> = [
      [["SELECT 1; DROP TABLE orders"], /multiple statements/],
      [["SELECT * FROM orders WHERE id = :nope"], /not in the tool inputSchema/],
      [["SELECT * FROM ghosts WHERE id = :order_id"], /unknown table "ghosts"/],
      [["SELECT pg_read_file('/etc/passwd') WHERE :order_id > 0"], /pg_/],
      [["SELECT * FROM orders WHERE id = $1"], /positional/],
    ];
    for (const [statements, re] of bad) {
      const { tools, report } = await proposeBindings([nonCrud], DDL, { generate: async () => ({ statements }) });
      expect(tools[0]!.binding.kind).toBe("simulated");
      expect(report.check_refund_eligibility!.origin).toBe("simulated");
      expect(report.check_refund_eligibility!.warnings.join(" ")).toMatch(re);
    }
  });

  it("downgrades when generate throws", async () => {
    const { report } = await proposeBindings([nonCrud], DDL, { generate: async () => { throw new Error("boom"); } });
    expect(report.check_refund_eligibility).toMatchObject({ origin: "simulated" });
    expect(report.check_refund_eligibility!.warnings[0]).toMatch(/boom/);
  });

  it("hints take precedence over rules and generate", async () => {
    const generate = vi.fn(async () => null);
    const { tools, report } = await proposeBindings([tool("get_order", { order_id: num }, ["order_id"])], DDL, {
      hints: { get_order: { statements: ["SELECT id, total FROM orders WHERE id = :order_id"], resultShape: "row" } },
      generate,
    });
    expect(report.get_order!.origin).toBe("hint");
    expect(sqlOf(tools[0]!)).toEqual(["SELECT id, total FROM orders WHERE id = :order_id"]);
    expect(generate).not.toHaveBeenCalled();
  });

  it("an unsafe hint is dropped and the rule tier is tried", async () => {
    const { report, tools } = await proposeBindings([tool("get_order", { order_id: num }, ["order_id"])], DDL, {
      hints: { get_order: { statements: ["DROP TABLE orders"] } },
    });
    expect(report.get_order!.origin).toBe("rule");
    expect(report.get_order!.warnings[0]).toMatch(/hint rejected/);
    expect(sqlOf(tools[0]!)[0]).toContain("FROM orders");
  });

  it("external tools are simulated with outbox recording", async () => {
    const send = tool("send_email", { to: str, subject: str }, ["to"], "external", "Send an email to a customer about their orders");
    send.outputSchema = { type: "object", properties: { message_id: str } };
    const { tools, report } = await proposeBindings([send], DDL);
    expect(report.send_email.origin).toBe("simulated");
    const b = tools[0]!.binding;
    expect(b).toMatchObject({ kind: "simulated", recordsOutbox: true });
    if (b.kind === "simulated") {
      expect(b.instructions.length).toBeLessThanOrEqual(4000);
      expect(b.instructions).toContain("send_email");
      expect(b.readsTables).toEqual(["customers", "orders"]);
    }
  });

  it("external tool with a hint uses the hint", async () => {
    const t = tool("log_event", { kind: str }, ["kind"], "external");
    const { report } = await proposeBindings([t], DDL, { hints: { log_event: { statements: ["INSERT INTO sandbox_outbox (kind, payload) VALUES (:kind, '{}'::jsonb) RETURNING *"], resultShape: "row" } } });
    expect(report.log_event!.origin).toBe("hint");
  });
});
