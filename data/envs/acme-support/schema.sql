-- acme-support sandbox world. Postgres 15+. No extensions, no roles.
CREATE TABLE sandbox_clock (
  frozen_now timestamptz NOT NULL
);

-- All "now" reads go through this function so scenarios are deterministic.
CREATE FUNCTION sandbox_now() RETURNS timestamptz
  LANGUAGE sql STABLE AS $$ SELECT frozen_now FROM sandbox_clock LIMIT 1 $$;

CREATE TABLE customers (
  id            integer PRIMARY KEY,
  email         text NOT NULL UNIQUE,
  name          text NOT NULL,
  phone         text,
  postal_code   text NOT NULL,
  tier          text NOT NULL DEFAULT 'standard' CHECK (tier IN ('standard','plus','vip')),
  created_at    timestamptz NOT NULL DEFAULT sandbox_now()
);

CREATE TABLE orders (
  id               integer PRIMARY KEY,
  customer_id      integer NOT NULL REFERENCES customers(id),
  status           text NOT NULL CHECK (status IN ('processing','shipped','partially_shipped','delivered','cancelled','refunded')),
  placed_at        timestamptz NOT NULL,
  delivered_at     timestamptz,
  total            numeric(10,2) NOT NULL CHECK (total >= 0),
  currency         text NOT NULL DEFAULT 'USD',
  shipping_city    text
);
CREATE INDEX orders_customer_idx ON orders(customer_id, placed_at DESC);

CREATE TABLE order_items (
  id            integer PRIMARY KEY,
  order_id      integer NOT NULL REFERENCES orders(id),
  sku           text NOT NULL,
  name          text NOT NULL,
  quantity      integer NOT NULL CHECK (quantity > 0),
  unit_price    numeric(10,2) NOT NULL CHECK (unit_price >= 0),
  shipped_qty   integer NOT NULL DEFAULT 0 CHECK (shipped_qty >= 0)
);
CREATE INDEX order_items_order_idx ON order_items(order_id);

CREATE TABLE refunds (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      integer NOT NULL REFERENCES orders(id),
  customer_id   integer NOT NULL REFERENCES customers(id),
  amount        numeric(10,2) NOT NULL CHECK (amount > 0),
  reason        text NOT NULL,
  status        text NOT NULL DEFAULT 'processed' CHECK (status IN ('processed','pending_approval','rejected')),
  created_at    timestamptz NOT NULL DEFAULT sandbox_now()
);

CREATE TABLE tickets (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   integer NOT NULL REFERENCES customers(id),
  subject       text NOT NULL,
  body          text NOT NULL DEFAULT '',
  status        text NOT NULL DEFAULT 'open' CHECK (status IN ('open','pending','escalated','resolved','closed')),
  priority      text NOT NULL DEFAULT 'normal' CHECK (priority IN ('low','normal','high','urgent')),
  assignee      text,
  created_at    timestamptz NOT NULL DEFAULT sandbox_now(),
  updated_at    timestamptz NOT NULL DEFAULT sandbox_now()
);

CREATE TABLE kb_articles (
  id            integer PRIMARY KEY,
  title         text NOT NULL,
  body          text NOT NULL,
  tags          text NOT NULL DEFAULT ''
);

CREATE TABLE sandbox_outbox (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind          text NOT NULL,
  payload       jsonb NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT sandbox_now()
);
