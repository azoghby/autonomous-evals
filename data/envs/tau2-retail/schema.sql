-- tau2-retail sandbox world (from tau2-bench retail domain, MIT, Sierra Research). Postgres 15+. No extensions, no roles.
-- sandbox_clock, sandbox_now() and sandbox_outbox come from the runtime preamble (runtime/world-sql.ts).
-- The retail domain has no wall-clock data ("all times are EST" in the policy but db.json stores none).

CREATE TABLE users (
  id          text PRIMARY KEY,               -- e.g. 'sara_doe_496'
  first_name  text NOT NULL,
  last_name   text NOT NULL,
  email       text NOT NULL,
  address1    text NOT NULL,
  address2    text NOT NULL DEFAULT '',
  city        text NOT NULL,
  state       text NOT NULL,
  country     text NOT NULL,
  zip         text NOT NULL
);
CREATE INDEX users_email_idx ON users(lower(email));
CREATE INDEX users_name_zip_idx ON users(lower(first_name), lower(last_name), zip);

CREATE TABLE user_payment_methods (
  id          text PRIMARY KEY,               -- e.g. 'credit_card_0000000', 'gift_card_0000000', 'paypal_0000000'
  user_id     text NOT NULL REFERENCES users(id),
  source      text NOT NULL CHECK (source IN ('credit_card','gift_card','paypal')),
  brand       text,                           -- credit_card only
  last_four   text,                           -- credit_card only
  balance     numeric(10,2) CHECK (balance IS NULL OR balance >= 0)  -- gift_card only
);
CREATE INDEX user_payment_methods_user_idx ON user_payment_methods(user_id);

CREATE TABLE products (
  id          text PRIMARY KEY,               -- product id (NOT an item id)
  name        text NOT NULL
);

CREATE TABLE product_variants (
  item_id     text PRIMARY KEY,               -- item id (NOT a product id)
  product_id  text NOT NULL REFERENCES products(id),
  options     jsonb NOT NULL,
  available   boolean NOT NULL,
  price       numeric(10,2) NOT NULL CHECK (price >= 0)
);
CREATE INDEX product_variants_product_idx ON product_variants(product_id);

CREATE TABLE orders (
  id                          text PRIMARY KEY,   -- e.g. '#W0000000' (leading '#')
  user_id                     text NOT NULL REFERENCES users(id),
  address1                    text NOT NULL,
  address2                    text NOT NULL DEFAULT '',
  city                        text NOT NULL,
  state                       text NOT NULL,
  country                     text NOT NULL,
  zip                         text NOT NULL,
  status                      text NOT NULL CHECK (status IN ('pending','pending (item modified)','processed','delivered','cancelled','exchange requested','return requested')),
  cancel_reason               text CHECK (cancel_reason IS NULL OR cancel_reason IN ('no longer needed','ordered by mistake')),
  exchange_items              jsonb,
  exchange_new_items          jsonb,
  exchange_payment_method_id  text,
  exchange_price_difference   numeric(10,2),
  return_items                jsonb,
  return_payment_method_id    text
);
CREATE INDEX orders_user_idx ON orders(user_id);

CREATE TABLE order_items (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- insertion order == line order
  order_id    text NOT NULL REFERENCES orders(id),
  product_id  text NOT NULL,
  item_id     text NOT NULL,
  name        text NOT NULL,
  price       numeric(10,2) NOT NULL CHECK (price >= 0),
  options     jsonb NOT NULL
);
CREATE INDEX order_items_order_idx ON order_items(order_id);

CREATE TABLE order_fulfillments (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      text NOT NULL REFERENCES orders(id),
  tracking_ids  jsonb NOT NULL,
  item_ids      jsonb NOT NULL
);
CREATE INDEX order_fulfillments_order_idx ON order_fulfillments(order_id);

CREATE TABLE order_payments (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- insertion order == payment_history order
  order_id           text NOT NULL REFERENCES orders(id),
  transaction_type   text NOT NULL CHECK (transaction_type IN ('payment','refund')),
  amount             numeric(10,2) NOT NULL CHECK (amount >= 0),
  payment_method_id  text NOT NULL
);
CREATE INDEX order_payments_order_idx ON order_payments(order_id);
